// Generate src/lang/tg/arabic-words.js from the Python package's word list.
//
//     npm run build:data
//
// The parsing follows `_word_list()` in src/nutq/lang/tg/arabic.py: text
// after "#" is a comment, blank lines are skipped, each line holds exactly
// two tab-separated fields (Cyrillic, Arabic). Cyrillic keys are lowercased
// and a later line wins; for Arabic -> Cyrillic the first line wins.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { pyStrip, splitLines } from "../src/core/text.js";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");
const source = join(root, "..", "src", "nutq", "lang", "tg", "data", "arabic_words.tsv");
const target = join(root, "src", "lang", "tg", "arabic-words.js");

const toArabic = new Map();
const toCyrillic = new Map();
splitLines(readFileSync(source, "utf8")).forEach((raw, index) => {
  const line = pyStrip(raw.split("#")[0]);
  if (!line) return;
  const parts = line.split("\t").filter((part) => pyStrip(part)).map(pyStrip);
  if (parts.length !== 2) {
    throw new Error(`${source}:${index + 1}: expected "cyrillic<TAB>arabic", got ${JSON.stringify(raw)}`);
  }
  const [cyrillic, arabic] = parts;
  toArabic.set(cyrillic.toLowerCase(), arabic);
  if (!toCyrillic.has(arabic)) toCyrillic.set(arabic, cyrillic);
});

const entries = (map) => [...map].map(([k, v]) => `  [${JSON.stringify(k)}, ${JSON.stringify(v)}],`).join("\n");
const header = "// Generated by scripts/build-data.mjs from " +
  relative(root, source).split("\\").join("/") + ". Do not edit.\n";
const output = `${header}
/** Cyrillic (lowercase) -> Perso-Arabic spellings the letter rules get wrong. */
export const TO_ARABIC = new Map([
${entries(toArabic)}
]);

/** Perso-Arabic -> Cyrillic (the first Cyrillic word listed for a spelling). */
export const TO_CYRILLIC = new Map([
${entries(toCyrillic)}
]);
`;
writeFileSync(target, output);
console.log(`wrote ${toArabic.size} words to ${relative(root, target)}`);
